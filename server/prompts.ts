/**
 * Потоковый парсер секций [TITLE], [BODY], [CTA], [TAGS]
 */
export class SectionStreamParser {
  private buffer = '';
  private currentSection: PostSection = 'TITLE';
  private startedAnySection = false;
  private onChunk: (section: PostSection, text: string) => void;

  constructor(onChunk: (section: PostSection, text: string) => void) {
    this.onChunk = onChunk;
  }

  public push(chunk: string) {
    this.buffer += chunk;
    this.processBuffer(false);
  }

  public flush() {
    this.processBuffer(true);
  }

  private processBuffer(isFinal: boolean) {
    const markerRegex = /\[(TITLE|BODY|CTA|TAGS)\]/g;

    while (true) {
      markerRegex.lastIndex = 0;
      const match = markerRegex.exec(this.buffer);

      if (match) {
        const beforeMarker = this.buffer.slice(0, match.index);
        if (beforeMarker && this.startedAnySection) {
          this.emitClean(this.currentSection, beforeMarker);
        }
        this.currentSection = match[1] as PostSection;
        this.startedAnySection = true;
        this.buffer = this.buffer.slice(match.index + match[0].length);
        if (this.buffer.startsWith('\r\n')) {
          this.buffer = this.buffer.slice(2);
        } else if (this.buffer.startsWith('\n')) {
          this.buffer = this.buffer.slice(1);
        }
        continue;
      }

      if (isFinal) {
        if (this.buffer.length > 0) {
          this.emitClean(this.currentSection, this.buffer);
          this.buffer = '';
        }
        break;
      }

      const lastBracket = this.buffer.lastIndexOf('[');
      if (lastBracket !== -1 && this.buffer.length - lastBracket < 10) {
        const safePart = this.buffer.slice(0, lastBracket);
        if (safePart.length > 0 && this.startedAnySection) {
          this.emitClean(this.currentSection, safePart);
        }
        this.buffer = this.buffer.slice(lastBracket);
      } else {
        if (this.buffer.length > 0 && this.startedAnySection) {
          this.emitClean(this.currentSection, this.buffer);
          this.buffer = '';
        } else if (!this.startedAnySection && this.buffer.length > 24) {
          this.startedAnySection = true;
          this.emitClean('TITLE', this.buffer);
          this.buffer = '';
        }
      }
      break;
    }
  }

  private emitClean(section: PostSection, text: string) {
    const cleaned = text.replace(/===VARIANT_\d+===/g, '');
    if (cleaned) {
      this.onChunk(section, cleaned);
    }
  }
}

